import { pluralizeRu } from '../plural'

const forms = ['операция', 'операции', 'операций'] as const

describe('pluralizeRu', () => {
  it.each([
    [0, 'операций'],
    [1, 'операция'],
    [2, 'операции'],
    [4, 'операции'],
    [5, 'операций'],
    [11, 'операций'],
    [12, 'операций'],
    [14, 'операций'],
    [20, 'операций'],
    [21, 'операция'],
    [22, 'операции'],
    [25, 'операций'],
    [111, 'операций'],
    [112, 'операций'],
    [121, 'операция'],
  ])('%i → %s', (count, expected) => {
    expect(pluralizeRu(count, forms)).toBe(expected)
  })
})
